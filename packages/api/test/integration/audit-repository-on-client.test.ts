describe('the card-number split rewrite (PgCallTranscriptTurnRepository.redactCardNumberTurns)', () => {
  let repo: PgCallTranscriptTurnRepository;
  beforeAll(() => {
    repo = new PgCallTranscriptTurnRepository(pool);
  });

  async function twoCallerTurns() {
    const callSid = `CA${crypto.randomUUID().replace(/-/g, '')}`;
    const sessionId = crypto.randomUUID();
    const first = await repo.recordTurn({
      tenantId: tenant.tenantId, callSid, sessionId, turnIndex: 0, speaker: 'caller', text: '4111 1111',
    });
    const second = await repo.recordTurn({
      tenantId: tenant.tenantId, callSid, sessionId, turnIndex: 2, speaker: 'caller', text: '1111 1111',
    });
    const rewrite = {
      tenantId: tenant.tenantId,
      callSid,
      sessionId,
      actorId: 'voice-session-store',
      turns: [
        { id: first.id, turnIndex: 0, text: CARD_NUMBER_PLACEHOLDER },
        { id: second.id, turnIndex: 2, text: CARD_NUMBER_PLACEHOLDER },
      ],
    };
    const texts = async () => (await repo.listByCallSid(tenant.tenantId, callSid)).map((r) => r.text);
    return { callSid, sessionId, rewrite, texts };
  }

  it('writes the audit row it wrote before, every column', async () => {
    const { callSid, sessionId, rewrite, texts } = await twoCallerTurns();
    const { result, window } = await during(() => repo.redactCardNumberTurns(rewrite));
    expect(result).toBe(2);
    expect(await texts()).toEqual([CARD_NUMBER_PLACEHOLDER, CARD_NUMBER_PLACEHOLDER]);
    const rows = await committedAuditRows(tenant.tenantId, CARD_NUMBER_SPLIT_REDACTED_EVENT, sessionId);
    expect(rows).toHaveLength(1);
    expectAuditRow(
      rows[0],
      {
        tenant_id: tenant.tenantId,
        actor_id: 'voice-session-store',
        actor_role: 'system',
        event_type: CARD_NUMBER_SPLIT_REDACTED_EVENT,
        entity_type: 'voice_session',
        entity_id: sessionId,
        correlation_id: GENERATED,
        metadata: { callSid, turnIndexes: [0, 2], rows: 2 },
      },
      window,
    );
  });

  it('a failing audit insert rolls the rewrite back: the rows keep their text', async () => {
    const { sessionId, rewrite, texts } = await twoCallerTurns();
    const condition = `NEW.event_type = '${CARD_NUMBER_SPLIT_REDACTED_EVENT}' AND NEW.entity_id = '${sessionId}'`;
    await withFailingAuditInsert(condition, async () => {
      await expect(repo.redactCardNumberTurns(rewrite)).rejects.toThrow(/injected audit insert failure/);
    });
    expect(await texts()).toEqual(['4111 1111', '1111 1111']);
    expect(await committedAuditRows(tenant.tenantId, CARD_NUMBER_SPLIT_REDACTED_EVENT, sessionId)).toEqual([]);
  });

  it('the audit row is in the rewrite transaction: a failure at COMMIT drops both', async () => {
    const { callSid, sessionId, rewrite, texts } = await twoCallerTurns();
    await withFailingCommit('call_transcript_turns', 'UPDATE', `NEW.call_sid = '${callSid}'`, async () => {
      await expect(repo.redactCardNumberTurns(rewrite)).rejects.toThrow(/injected commit failure/);
    });
    expect(await texts()).toEqual(['4111 1111', '1111 1111']);
    expect(await committedAuditRows(tenant.tenantId, CARD_NUMBER_SPLIT_REDACTED_EVENT, sessionId)).toEqual([]);
  });
});

describe('the shadow-comparison purge (PgShadowComparisonRetentionRepository.purgeDue)', () => {
  let store: PgShadowComparisonStore;
  let repo: PgShadowComparisonRetentionRepository;
  const NOW = new Date();
  beforeAll(() => {
    store = new PgShadowComparisonStore(pool);
    repo = new PgShadowComparisonRetentionRepository(pool);
  });

  async function save(tenantId: string, taskType: string, sampledAt: Date): Promise<void> {
    const result: ShadowComparisonResult = {
      id: crypto.randomUUID(),
      comparisonGroupId: crypto.randomUUID(),
      taskType,
      primaryResponse: {
        content: 'primary reply',
        model: 'primary-model',
        provider: 'p',
        tokenUsage: { input: 1, output: 2, total: 3 },
        latencyMs: 10,
      },
      shadowResponse: {
        content: 'shadow reply',
        model: 'shadow-model',
        provider: 's',
        tokenUsage: { input: 4, output: 5, total: 9 },
        latencyMs: 20,
      },
      sampledAt,
      tenantId,
    };
    await store.save(result);
  }

  async function dueRows() {
    const t = await seedTenant();
    const oldest = new Date(NOW.getTime() - WINDOW_DAYS * DAY_MS - 3 * DAY_MS);
    const newest = new Date(NOW.getTime() - WINDOW_DAYS * DAY_MS - 2 * DAY_MS);
    await save(t.tenantId, 'classify_intent', oldest);
    await save(t.tenantId, 'summarize_conversation', newest);
    const remaining = async () =>
      (await pool.query('SELECT 1 FROM shadow_comparisons WHERE tenant_id = $1', [t.tenantId])).rowCount;
    const purge = () =>
      repo.purgeDue(t.tenantId, NOW, WINDOW_DAYS, 500, (rows) =>
        buildShadowComparisonPurgeAudit(t.tenantId, rows, WINDOW_DAYS),
      );
    return { t, oldest, newest, remaining, purge };
  }

  it('writes the audit row it wrote before, every column', async () => {
    const { t, oldest, newest, remaining, purge } = await dueRows();
    const { result, window } = await during(purge);
    expect(result.audited).toBe(true);
    expect(result.rows).toHaveLength(2);
    expect(await remaining()).toBe(0);
    const rows = await committedAuditRows(t.tenantId, SHADOW_COMPARISON_PURGED_EVENT, t.tenantId);
    expect(rows).toHaveLength(1);
    expectAuditRow(
      rows[0],
      {
        tenant_id: t.tenantId,
        actor_id: 'shadow-comparison-retention-worker',
        actor_role: 'system',
        event_type: SHADOW_COMPARISON_PURGED_EVENT,
        entity_type: 'tenant',
        entity_id: t.tenantId,
        correlation_id: GENERATED,
        metadata: {
          reason: 'past_retention',
          retentionDays: WINDOW_DAYS,
          rowsPurged: 2,
          byTaskType: { classify_intent: 1, summarize_conversation: 1 },
          oldestCreatedAt: oldest.toISOString(),
          newestCreatedAt: newest.toISOString(),
        },
      },
      window,
    );
  });

  it('the audit row is in the DELETE transaction: a failure at COMMIT drops both', async () => {
    const { t, remaining, purge } = await dueRows();
    await withFailingCommit('shadow_comparisons', 'DELETE', `OLD.tenant_id = '${t.tenantId}'::uuid`, async () => {
      await expect(purge()).rejects.toThrow(/injected commit failure/);
    });
    expect(await remaining()).toBe(2);
    expect(await committedAuditRows(t.tenantId, SHADOW_COMPARISON_PURGED_EVENT, t.tenantId)).toEqual([]);
  });
});

describe('the demo platform audit (writePlatformAudit on the platform transaction)', () => {
  /** The platform transaction's context: the platform tenant GUC, no role (demo/reset.ts, demo/service.ts). */
  async function inPlatformTransaction(
    outcome: 'COMMIT' | 'ROLLBACK',
    fn: (client: PoolClient) => Promise<void>,
  ): Promise<void> {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await setPlatformTenantContext(client);
      await fn(client);
      await client.query(outcome);
    } catch (err) {
      await client.query('ROLLBACK').catch(() => undefined);
      throw err;
    } finally {
      client.release();
    }
  }

  it('writes the audit row it wrote before, every column, when the caller commits', async () => {
    const entityId = `u7-04a-${RUN}-platform-commit`;
    const correlationId = crypto.randomUUID();
    const { window } = await during(() =>
      inPlatformTransaction('COMMIT', (client) =>
        writePlatformAudit(client, {
          eventType: 'demo.u7_04a_probe',
          entityType: 'demo_call',
          entityId,
          correlationId,
          metadata: { cap: 'calls', level: 1, rule: 'probe' },
        }),
      ),
    );
    const rows = await committedAuditRows(DEMO_PLATFORM_TENANT_ID, 'demo.u7_04a_probe', entityId);
    expect(rows).toHaveLength(1);
    expectAuditRow(
      rows[0],
      {
        tenant_id: DEMO_PLATFORM_TENANT_ID,
        actor_id: DEMO_PLATFORM_ACTOR_ID,
        actor_role: 'system',
        event_type: 'demo.u7_04a_probe',
        entity_type: 'demo_call',
        entity_id: entityId,
        correlation_id: correlationId,
        metadata: { cap: 'calls', level: 1, rule: 'probe' },
      },
      window,
    );
  });

  it("is in the caller's transaction: invisible to other sessions until COMMIT, dropped by the caller's ROLLBACK", async () => {
    const entityId = `u7-04a-${RUN}-platform-rollback`;
    await inPlatformTransaction('ROLLBACK', async (client) => {
      await writePlatformAudit(client, { eventType: 'demo.u7_04a_probe', entityType: 'demo_call', entityId });
      const own = await client.query('SELECT metadata, correlation_id FROM audit_events WHERE entity_id = $1', [entityId]);
      expect(own.rows).toHaveLength(1);
      expect(own.rows[0].metadata).toEqual({});
      expect(own.rows[0].correlation_id).toMatch(UUID_V4);
      expect(await committedAuditRows(DEMO_PLATFORM_TENANT_ID, 'demo.u7_04a_probe', entityId)).toEqual([]);
    });
    expect(await committedAuditRows(DEMO_PLATFORM_TENANT_ID, 'demo.u7_04a_probe', entityId)).toEqual([]);
  });
});

