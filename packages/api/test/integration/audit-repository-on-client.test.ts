/**
 * Write with `write` on a client under the runtime role and `tenantId`'s
 * context (as withTenantTransaction applies it), read the row back on that
 * client, and roll back.
 */
async function writeAndReadBack(
  tenantId: string,
  id: string,
  write: (client: PoolClient) => Promise<unknown>,
): Promise<Record<string, unknown>[]> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query(TENANT_CONTEXT_WITH_ROLE_SQL, [tenantId]);
    await write(client);
    const { rows } = await client.query(
      'SELECT *, metadata::text AS metadata_text FROM audit_events WHERE id = $1',
      [id],
    );
    return rows;
  } finally {
    await client.query('ROLLBACK').catch(() => undefined);
    client.release();
  }
}

describe('insertAuditEventOnClient (real Postgres, RLS_RUNTIME_ROLE=true)', () => {
  it('writes the row the raw insert wrote, column for column: an event from createAuditEvent', async () => {
    const event = createAuditEvent({
      tenantId: tenant.tenantId,
      actorId: 'u7-04a-test',
      actorRole: 'system',
      eventType: 'u7_04a.probe',
      entityType: 'probe',
      entityId: `u7-04a-${RUN}-oracle-1`,
      correlationId: crypto.randomUUID(),
      metadata: { nested: { list: [1, 'two', null], flag: true }, text: 'café ☕', ratio: 1.5, empty: {} },
    });
    const raw = await writeAndReadBack(tenant.tenantId, event.id, (c) => c.query(RAW_INSERT_SQL, rawInsertParams(event)));
    const viaRepository = await writeAndReadBack(tenant.tenantId, event.id, (c) => insertAuditEventOnClient(c, event));
    expect(raw).toHaveLength(1);
    expect(viaRepository).toEqual(raw);
  });

  it('writes the row the raw insert wrote for an event with no metadata and no correlation id ({} and NULL)', async () => {
    // AuditEvent allows both to be absent; the raw inserts wrote '{}' and
    // NULL (`?? {}`, `?? null`), unlike PgAuditRepository.create's NULL
    // metadata, and the on-client insert keeps the raw inserts' values.
    const event: AuditEvent = {
      id: crypto.randomUUID(),
      tenantId: tenant.tenantId,
      actorId: 'u7-04a-test',
      actorRole: 'system',
      eventType: 'u7_04a.probe',
      entityType: 'probe',
      entityId: `u7-04a-${RUN}-oracle-2`,
      createdAt: new Date('2026-10-25T12:34:56.789Z'),
    };
    const raw = await writeAndReadBack(tenant.tenantId, event.id, (c) => c.query(RAW_INSERT_SQL, rawInsertParams(event)));
    const viaRepository = await writeAndReadBack(tenant.tenantId, event.id, (c) => insertAuditEventOnClient(c, event));
    expect(raw).toHaveLength(1);
    expect(raw[0]).toMatchObject({ metadata: {}, metadata_text: '{}', correlation_id: null });
    expect((raw[0].created_at as Date).toISOString()).toBe('2026-10-25T12:34:56.789Z');
    expect(viaRepository).toEqual(raw);
  });

  it("writes on the caller's transaction: invisible to other sessions before COMMIT, dropped by ROLLBACK, kept by COMMIT", async () => {
    const make = (n: number) =>
      createAuditEvent({
        tenantId: tenant.tenantId,
        actorId: 'u7-04a-test',
        actorRole: 'system',
        eventType: 'u7_04a.probe',
        entityType: 'probe',
        entityId: `u7-04a-${RUN}-tx-${n}`,
      });
    const committedCount = async (id: string) =>
      (await pool.query('SELECT 1 FROM audit_events WHERE id = $1', [id])).rowCount;

    for (const outcome of ['ROLLBACK', 'COMMIT'] as const) {
      const event = make(outcome === 'ROLLBACK' ? 1 : 2);
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        await client.query(TENANT_CONTEXT_WITH_ROLE_SQL, [tenant.tenantId]);
        await insertAuditEventOnClient(client, event);
        expect((await client.query('SELECT 1 FROM audit_events WHERE id = $1', [event.id])).rowCount).toBe(1);
        expect(await committedCount(event.id)).toBe(0);
        await client.query(outcome);
      } finally {
        client.release();
      }
      expect(await committedCount(event.id)).toBe(outcome === 'COMMIT' ? 1 : 0);
    }
  });
});

