/** The audit rows for one entity, as another session sees them (committed only). */
async function committedAuditRows(
  tenantId: string,
  eventType: string,
  entityId: string,
): Promise<Record<string, unknown>[]> {
  const { rows } = await pool.query(
    `SELECT * FROM audit_events
      WHERE tenant_id = $1 AND event_type = $2 AND entity_id = $3
      ORDER BY created_at ASC`,
    [tenantId, eventType, entityId],
  );
  return rows;
}

interface ExpectedAuditRow {
  tenant_id: string;
  actor_id: string;
  actor_role: string;
  event_type: string;
  entity_type: string;
  entity_id: string;
  correlation_id: string | null | typeof GENERATED;
  metadata: Record<string, unknown>;
}

/**
 * Every column of `row`, against what the site's raw insert wrote: a v4 id, a
 * created_at taken during the call, the caller-supplied or generated
 * correlation id, and the rest exactly.
 */
function expectAuditRow(
  row: Record<string, unknown>,
  expected: ExpectedAuditRow,
  window: { before: Date; after: Date },
): void {
  expect(Object.keys(row).sort()).toEqual(AUDIT_COLUMNS);
  const { id, created_at: createdAt, correlation_id: correlationId, ...rest } = row;
  expect(id).toMatch(UUID_V4);
  expect(createdAt).toBeInstanceOf(Date);
  expect((createdAt as Date).getTime()).toBeGreaterThanOrEqual(window.before.getTime());
  expect((createdAt as Date).getTime()).toBeLessThanOrEqual(window.after.getTime());
  const { correlation_id: expectedCorrelation, ...expectedRest } = expected;
  if (expectedCorrelation === GENERATED) expect(correlationId).toMatch(UUID_V4);
  else expect(correlationId).toBe(expectedCorrelation);
  expect(rest).toEqual(expectedRest);
}

async function during<T>(fn: () => Promise<T>): Promise<{ result: T; window: { before: Date; after: Date } }> {
  const before = new Date();
  const result = await fn();
  return { result, window: { before, after: new Date() } };
}

async function dropTrigger(name: string, table: string): Promise<void> {
  await pool.query(`DROP TRIGGER IF EXISTS ${name} ON ${table}`);
  await pool.query(`DROP FUNCTION IF EXISTS ${name}()`);
}

/** Run `body` while every audit_events insert matching `condition` (over NEW) raises. */
async function withFailingAuditInsert<T>(condition: string, body: () => Promise<T>): Promise<T> {
  const name = `u7_04a_audit_fail_${RUN}_${triggerSeq++}`;
  await pool.query(
    `CREATE FUNCTION ${name}() RETURNS trigger LANGUAGE plpgsql AS $f$
       BEGIN
         IF ${condition} THEN
           RAISE EXCEPTION 'injected audit insert failure';
         END IF;
         RETURN NEW;
       END $f$`,
  );
  await pool.query(`CREATE TRIGGER ${name} BEFORE INSERT ON audit_events FOR EACH ROW EXECUTE FUNCTION ${name}()`);
  try {
    return await body();
  } finally {
    await dropTrigger(name, 'audit_events');
  }
}

/**
 * Run `body` while a transaction that wrote a `table` row matching `condition`
 * fails at COMMIT: a deferred constraint trigger, so every statement of the
 * transaction (the site's write and its audit insert) has already succeeded
 * when it raises.
 */
async function withFailingCommit<T>(
  table: string,
  events: string,
  condition: string,
  body: () => Promise<T>,
): Promise<T> {
  const name = `u7_04a_commit_fail_${RUN}_${triggerSeq++}`;
  await pool.query(
    `CREATE FUNCTION ${name}() RETURNS trigger LANGUAGE plpgsql AS $f$
       BEGIN
         IF ${condition} THEN
           RAISE EXCEPTION 'injected commit failure';
         END IF;
         RETURN NULL;
       END $f$`,
  );
  await pool.query(
    `CREATE CONSTRAINT TRIGGER ${name} AFTER ${events} ON ${table}
       DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ${name}()`,
  );
  try {
    return await body();
  } finally {
    await dropTrigger(name, table);
  }
}

