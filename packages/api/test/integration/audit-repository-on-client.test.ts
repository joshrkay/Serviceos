/**
 * U7-04a — the audit repository's on-client insert, against real Postgres
 * with RLS_RUNTIME_ROLE=true.
 *
 * Four writers used to run their own `INSERT INTO audit_events` on a client
 * they already held: the card-number split rewrite
 * (`PgCallTranscriptTurnRepository.redactCardNumberTurns`), the
 * shadow-comparison purge (`PgShadowComparisonRetentionRepository.purgeDue`),
 * the demo platform transaction (`writePlatformAudit`) and the entity-alias
 * repository (`activateFromApprovedProposal` / `deactivate`). They now call
 * `insertAuditEventOnClient(client, event)` from `audit/pg-audit.ts`. This
 * file pins that the move changed nothing:
 *
 *   1. The on-client insert writes the row the raw statement wrote. The raw
 *      statement is kept below verbatim as the oracle; both write the same
 *      event (each in a rolled-back transaction) and the two rows read back
 *      equal, column for column.
 *   2. It writes on the caller's transaction: no other session sees the row
 *      before COMMIT, and a ROLLBACK drops it.
 *   3. Per site, through the production entry point: the audit row (every
 *      column, every value) and its transaction. A failing audit insert rolls
 *      the site's own write back, and a failure at COMMIT (a deferred
 *      constraint trigger on the site's own table) drops the write AND the
 *      audit row. An audit row written on any other connection would survive
 *      that COMMIT failure, so this is what proves "same transaction".
 *
 * Part 3 passes on main before the move as well: it is the "identical to
 * before" pin, not a test of the new function. The shadow purge's
 * failing-audit-insert case is pinned in shadow-comparisons-retention.test.ts
 * and the split rewrite's failing-row case in
 * card-number-split-across-turns.test.ts; they are not repeated here.
 *
 * Every file shares one database, so assertions are scoped to this file's
 * tenants and entity ids. The triggers are scoped to this file's rows and
 * dropped in `finally`; integration files run one at a time.
 */
